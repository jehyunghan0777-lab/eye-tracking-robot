static void process_sample_block(
    uint32_t start_index
)
{
    for (
        uint32_t sample = 0U;
        sample < SAMPLES_PER_HALF;
        sample++
    )
    {
        uint32_t buffer_index =
            start_index
            + sample * ADC_CHANNEL_COUNT;

        SEMG_Class new_prediction;

        bool prediction_changed =
            SEMG_Classifier_AddSample(
                adc_dma_buffer[
                    buffer_index
                ],
                adc_dma_buffer[
                    buffer_index + 1U
                ],
                &new_prediction
            );

        if (prediction_changed)
        {
            pending_prediction =
                new_prediction;

            prediction_pending = 1U;
        }
    }
}


static void try_transmit_prediction(void)
{
    if (prediction_pending == 0U)
    {
        return;
    }

    int written = snprintf(
        usb_tx_buffer,
        sizeof(usb_tx_buffer),
        "SEMG,%s\r\n",
        SEMG_ClassName(
            pending_prediction
        )
    );

    if (
        written <= 0
        || written
            >= (int)sizeof(usb_tx_buffer)
    )
    {
        prediction_pending = 0U;
        return;
    }

    if (
        CDC_Transmit_FS(
            (uint8_t *)usb_tx_buffer,
            (uint16_t)written
        )
        == USBD_OK
    )
    {
        prediction_pending = 0U;
    }
}

